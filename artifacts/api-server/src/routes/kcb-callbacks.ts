import { Router, type Request, type Response } from "express";
import { db } from "@workspace/db";
import { ApiError } from "../lib/core";
import { decryptCredentials, digest, systemActor } from "../lib/integrations/security";
import { normalizeKcb, verifyKcbSignature } from "../lib/integrations/kcb";
import { kcbAccountForToken } from "../lib/bank-accounts";
import { ingest } from "../lib/payments/pipeline";

const router = Router();
export function kcbHandler(kind: "account" | "till") {
  return async (req: Request, res: Response) => {
    const token = String(req.params.token);
    // Bank-tab accounts first; integration configs saved before the Bank tab keep working.
    const bank = await kcbAccountForToken(token);
    let schoolId: string, key: string, receiving: { accountNumber?: string; tillBusinessKey?: string };
    if (bank) {
      schoolId = bank.account.schoolId; key = bank.kcbPublicKey;
      receiving = { accountNumber: bank.account.accountNumber, tillBusinessKey: bank.account.collectionType === "kcb_till" ? bank.account.collectionNumber ?? undefined : undefined };
    } else {
      const config = await db.integrationConfig.findUnique({ where: { callbackTokenHash: digest(token) } });
      if (!config?.enabled || config.provider !== "bank") throw new ApiError(404, "KCB callback configuration not found");
      const credentials = decryptCredentials(config.encryptedCredentials);
      if (!credentials.kcbPublicKey) throw new ApiError(503, "KCB signing public key is not configured");
      schoolId = config.schoolId; key = credentials.kcbPublicKey;
      receiving = { ...(config.publicConfig as { accountNumber?: string }), tillBusinessKey: credentials.tillBusinessKey };
    }
    verifyKcbSignature(key, req.rawBody ?? Buffer.alloc(0), req.get("Signature") ?? "");
    const normalized = normalizeKcb(kind, req.body, receiving);
    // Acknowledge only after durable ingest. Matching/ledger posting uses the
    // existing worker; an acknowledgement is not a claim of student allocation.
    if (!normalized.timeTrusted) await db.integrationEvent.create({ data: { schoolId, provider: "kcb", event: "timestamp_unreadable", status: "held_for_review", detail: { transactionId: normalized.input.providerTxnId } } });
    const payment = await ingest(await systemActor(schoolId), normalized.input, normalized.timeTrusted ? "kcb_signed_notification" : "callback_hold", req.body);
    if (bank) await db.bankAccount.update({ where: { id: bank.account.id }, data: { lastNotificationAt: new Date(), ...(bank.account.notificationStatus !== "live" ? { notificationStatus: "live", liveAt: new Date() } : {}) } });
    // KCB's till acknowledgement carries "a unique transaction id generated by your system".
    const ack: any = normalized.acknowledgement;
    if (ack.responsePayload) ack.responsePayload.transactionInfo.transactionId = payment.id;
    res.json(ack);
  };
}
for (const kind of ["account", "till"] as const) {
  router.post(`/integrations/kcb/${kind}-notification/:token`, kcbHandler(kind));
}
export default router;
